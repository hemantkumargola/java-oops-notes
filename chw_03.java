/*### 3. What is a Class?

**Definition:**
A **class** is a blueprint or template used to create objects.

**Example:**

*/



class chw_03 {
    String name;
    int age;

    void study() {
        System.out.println("Student is studying");
    }
}

// Here, `Student` is a **class** that contains **data (name, age)** and a **method (study)**.
 