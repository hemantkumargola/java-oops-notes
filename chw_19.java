/*19. Encapsulation vs Abstraction in Java

1. Encapsulation
- Encapsulation means wrapping data and methods into a single unit called a class.
- It focuses on data hiding and controlled access.
- It is achieved using private variables and getter/setter methods.

2. Abstraction
- Abstraction means hiding implementation details and showing only essential features.
- It focuses on what an object does, not how it does it.
- It is achieved using abstract classes and interfaces.

3. Main Differences

Encapsulation:
- Protects and controls access to data.
- Uses access modifiers, getters and setters.
- Example: Private age variable in Student class.

Abstraction:
- Hides implementation details.
- Uses abstract classes and interfaces.
- Example: Vehicle interface with a start() method.

4. Interview Answer

Q. What is the difference between Encapsulation and Abstraction?

Answer:
Encapsulation focuses on wrapping data and methods into a single unit and controlling access to data, whereas abstraction focuses on hiding implementation details and showing only essential functionality.

5. Easy Trick to Remember

Encapsulation = Data Hiding + Controlled Access

Abstraction = Hiding Implementation Details*/