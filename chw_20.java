// 20. Advantages of Encapsulation in Java

/*
1. Data Hiding:
   Protects data using private variables.

2. Data Security:
   Prevents direct access to class variables.

3. Controlled Access:
   Provides controlled access through getter
   and setter methods.

4. Code Maintainability:
   Makes code easier to modify and maintain.

5. Flexibility:
   Internal implementation can be changed
   without affecting other classes.

6. Data Validation:
   Validates data before modifying variables.

7. Reusability:
   Encapsulated classes can be reused in
   different parts of an application.

Interview Answer:
The main advantages of encapsulation are
data hiding, data security, controlled access,
maintainability, flexibility, and data validation.
*/
