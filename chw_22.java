// 22. Types of Inheritance in Java

/*
There are 5 types of inheritance:

1. Single Inheritance:
   One child class inherits one parent class.

2. Multilevel Inheritance:
   A class inherits from a child class,
   forming a chain of inheritance.

3. Hierarchical Inheritance:
   Multiple child classes inherit from
   one parent class.

4. Multiple Inheritance:
   One child class inherits from multiple
   parent classes.
   Java does not support multiple inheritance
   through classes, but supports it through
   interfaces.

5. Hybrid Inheritance:
   A combination of two or more types
   of inheritance.
   Java supports hybrid inheritance using
   interfaces when needed.

Interview Answer:
Java supports single, multilevel, and
hierarchical inheritance through classes.
Multiple and hybrid inheritance can be
achieved using interfaces.
*/
